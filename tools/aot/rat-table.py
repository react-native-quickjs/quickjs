#!/usr/bin/env python3
"""rat-table.py: build the return-address table of a stack-map unit from its line tables.

usage: rat-table.py SIDE.rat OUT.c OBJ.o...
For every call instruction in the section aottext of the objects, the instruction after it is a return address. llvm-symbolizer (with
inlining) names its source location; the generator tagged each op with `#line <pc+1> "<function digest hex>"` (or line 1000000+i with a chain in
SIDE for the ops of planned inlined copies). The table is keyed by (symbol, offset) so it does not depend on where the linker puts the text.
"""
import re, subprocess, sys, collections

side, out, objs = sys.argv[1], sys.argv[2], sys.argv[3:]
chains = {}
import os
for ln in (open(side) if os.path.exists(side) else []):
    t = ln.split()
    if t[0] != 'C':
        continue
    hexn, line = t[1], int(t[2])
    fr, i = [], 3
    while t[i] != 'ROOT':
        fr.append((t[i], int(t[i + 1])))
        i += 2
    fr.append((hexn, int(t[i + 1])))
    chains[(hexn, line)] = fr

ents = []  # (symbol, offset, frames)
# Addresses in a relocatable object are per section, so the line rows of other sections (which also start at 0) would answer for them: the object is linked
# to a throwaway image first (nothing resolved, nothing run) and the image is read. Symbols and offsets in it are the object's own.
import tempfile, shutil
tmpd = tempfile.mkdtemp(dir=os.path.dirname(os.path.abspath(out)))
for o_orig in objs:
    o = os.path.join(tmpd, os.path.basename(o_orig) + '.img')
    r_ = subprocess.run(['clang', '-nostdlib', '-static', '-fuse-ld=lld', '-Wl,--unresolved-symbols=ignore-all', '-Wl,--entry=0', '-Wl,--noinhibit-exec', o_orig, '-o', o], capture_output=True, text=True)
    if r_.returncode != 0 or not os.path.exists(o):
        sys.stderr.write('rat-table: link of %s failed: %s\n' % (o_orig, r_.stderr[-300:]))
        sys.exit(1)
    dis = subprocess.run(['llvm-objdump-19' if False else 'objdump', '-d', '-r', '--no-show-raw-insn', '-j', 'aottext', o], capture_output=True, text=True).stdout
    sym, base, addrs = None, 0, []
    rows = []
    for l in dis.split('\n'):
        m = re.match(r'^([0-9a-f]+) <(.+)>:$', l)
        if m:
            sym, base = m.group(2), int(m.group(1), 16)
            continue
        m = re.match(r'^\s*([0-9a-f]+):\s+(call|callq)\b', l)
        if m and sym:
            rows.append((sym, int(m.group(1), 16) - base, int(m.group(1), 16)))
    # the next instruction address of each call: take it from the following line
    nxt = {}
    prev = None
    for l in dis.split('\n'):
        m = re.match(r'^\s*([0-9a-f]+):\s+(?!R_X86)', l)
        if m:
            a = int(m.group(1), 16)
            if prev is not None:
                nxt[prev] = a
            prev = a
    q = [nxt[a] for (_, _, a) in rows if a in nxt]
    if not q:
        continue
    inp = '\n'.join('0x%x' % (a - 1) for a in q) + '\n'
    res = subprocess.run(['llvm-symbolizer', '--obj=' + o, '--inlining', '--functions=none', '--basenames'], input=inp, capture_output=True, text=True).stdout
    blocks = res.split('\n\n')
    for (s_, off, a), ra, blk in zip([r for r in rows if r[2] in nxt], q, blocks):
        frames = []
        for ln in blk.strip().split('\n'):
            m = re.match(r'^(\S+):(\d+):\d+$', ln.strip())
            if not m:
                continue
            f, line = m.group(1), int(m.group(2))
            if f == 'NOFRAME':
                continue
            if line >= 0x40000000 and (f, (line - 0x40000000) >> 12) in chains:
                frames += chains[(f, (line - 0x40000000) >> 12)]
            elif line < 0x40000000 and re.fullmatch(r'[0-9a-f]{32}', f):
                frames.append((f, line >> 12))
        if frames:
            ents.append((s_, nxt[a] - (a - off), frames))

with open(out, 'w') as c:
    c.write('/* generated by rat-table.py */\n#include <stdint.h>\n#include <stddef.h>\n')
    c.write('typedef struct { uint8_t d[16]; int32_t pc; } JSAotRatFr;\ntypedef struct { const char *ra; uint16_t first, n; } JSAotRatEnt;\n')
    c.write('extern void qjs_aot_set_rat(const JSAotRatEnt *, size_t, const JSAotRatFr *);\n')
    syms = sorted(set(e[0] for e in ents))
    for s_ in syms:
        c.write('extern char %s[];\n' % s_)
    c.write('static const JSAotRatFr rat_fr[] = {\n')
    ent_lines, k = [], 0
    for (s_, off, fr) in ents:
        ent_lines.append('  { %s + %d, %d, %d },\n' % (s_, off, k, len(fr)))
        for (h, pc) in fr:
            c.write('  {{' + ','.join('0x' + h[i:i + 2] for i in range(0, 32, 2)) + '}, %d},\n' % pc)
        k += len(fr)
    c.write('};\nstatic const JSAotRatEnt rat_ent[] = {\n' + ''.join(ent_lines) + '};\n')
    c.write('static void __attribute__((constructor)) rat_reg(void) { qjs_aot_set_rat(rat_ent, %d, rat_fr); }\n' % len(ents))
shutil.rmtree(tmpd, ignore_errors=True)
print('rat entries', len(ents), file=sys.stderr)
