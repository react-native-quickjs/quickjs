/**
 * FormattedParts -> `[{type, value}, ...]`.
 *
 * Every offset is clamped rather than trusted. A backend that miscomputes an
 * offset should produce a wrong string, not an out-of-bounds read, and this is
 * the only place a platform's arithmetic becomes a memory access.
 */
JSValue partsToArray(JSContext *ctx, const FormattedParts &p) {
  const auto textLen = static_cast<int32_t>(p.text.size());
  JSValue arr = JS_NewArray(ctx);
  for (size_t i = 0; i < p.parts.size(); i++) {
    const Part &part = p.parts[i];
    auto type = static_cast<int32_t>(part.type);
    if (type < 0 || type >= static_cast<int32_t>(PartType::Count)) {
      type = static_cast<int32_t>(PartType::Unknown);
    }
    int32_t begin = part.begin < 0 ? 0 : part.begin;
    if (begin > textLen) begin = textLen;
    int32_t end = part.end > textLen ? textLen : part.end;
    if (end < begin) end = begin;

    JSValue o = JS_NewObject(ctx);
    JS_SetPropertyStr(ctx, o, "type", JS_NewString(ctx, kPartTypeNames[type]));
    JS_SetPropertyStr(
        ctx, o, "value",
        JS_NewStringUTF16(
            ctx, reinterpret_cast<const uint16_t *>(p.text.data()) + begin,
            static_cast<size_t>(end - begin)));
    JS_SetPropertyUint32(ctx, arr, static_cast<uint32_t>(i), o);
  }
  return arr;
}

JSValue js_dtfFormatToParts(
    JSContext *ctx, JSValueConst, int argc, JSValueConst *argv) {
  if (argc < 2) {
    return JS_ThrowTypeError(ctx, "dtfFormatToParts expects (handle, ms)");
  }
  DateTimeFormatter *dtf = handleOf(ctx, argv[0]);
  if (dtf == nullptr) return JS_EXCEPTION;
  double ms = 0;
  if (JS_ToFloat64(ctx, &ms, argv[1]) < 0) return JS_EXCEPTION;

  FormattedParts p;
  if (!dtf->formatToParts(ms, p)) {
    return JS_ThrowRangeError(ctx, "date formatting failed");
  }
  return partsToArray(ctx, p);
}

