/*
 * dtfOpen(locale, calendar, numberingSystem, timeZone, hourCycle, skeleton,
 *         dateStyle, timeStyle) -> handle | null
 *
 * Eight positional arguments rather than an options object, deliberately. This
 * crosses once per formatter and never per format() call, so its cost is
 * irrelevant; what matters is that the platform layer receives a plain struct
 * and never reads a JavaScript object, which is what keeps the JNI and
 * Objective-C code free of any engine knowledge.
 */
JSValue js_dtfOpen(JSContext *ctx, JSValueConst, int argc, JSValueConst *argv) {
  auto arg = [&](int i) { return i < argc ? argv[i] : JS_UNDEFINED; };
  DateTimeOptions opts;
  opts.locale = utf8Arg(ctx, arg(0));
  opts.calendar = utf8Arg(ctx, arg(1));
  opts.numberingSystem = utf8Arg(ctx, arg(2));
  opts.timeZone = utf8Arg(ctx, arg(3));
  opts.hourCycle = utf8Arg(ctx, arg(4));
  opts.skeleton = utf8Arg(ctx, arg(5));
  opts.dateStyle = utf8Arg(ctx, arg(6));
  opts.timeStyle = utf8Arg(ctx, arg(7));
  if (opts.locale.empty()) return JS_NULL;

  std::unique_ptr<DateTimeFormatter> dtf = platform()->openDateTimeFormat(opts);
  if (!dtf) return JS_NULL;

  return DtfHandle::wrap(ctx, std::move(dtf));
}

JSValue js_dtfFormat(
    JSContext *ctx, JSValueConst, int argc, JSValueConst *argv) {
  if (argc < 2) return JS_ThrowTypeError(ctx, "dtfFormat expects (handle, ms)");
  DateTimeFormatter *dtf = handleOf(ctx, argv[0]);
  if (dtf == nullptr) return JS_EXCEPTION;
  double ms = 0;
  if (JS_ToFloat64(ctx, &ms, argv[1]) < 0) return JS_EXCEPTION;
  std::u16string out;
  if (!dtf->format(ms, out)) {
    return JS_ThrowRangeError(ctx, "date formatting failed");
  }
  return makeString(ctx, out);
}

