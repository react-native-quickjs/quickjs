#if defined(RNQJS_INTL_COUNTERS) && RNQJS_INTL_COUNTERS
/*
 * Hit-rate counters, off by default and free when off.
 *
 * `blobLoads` versus `sourceLoads` is the one that matters: this project has
 * shipped a fast path with zero hits before, and "the bytecode blob is being
 * used" is exactly the kind of claim that is easy to believe and wrong. If
 * sourceLoads is non-zero in a shipping build, the build-time compile step did
 * not run or the blob is stale, and the startup number in the docs is fiction.
 */
struct Counters {
  unsigned long accessorInstalls = 0;
  unsigned long materializations = 0;
  unsigned long blobLoads = 0;
  unsigned long sourceLoads = 0;
  unsigned long setterOverrides = 0;
};
Counters g_counters;
#define RNQJS_INTL_COUNT(field) (++g_counters.field)
#else
#define RNQJS_INTL_COUNT(field) ((void)0)
#endif

/**
 * Deserializes and evaluates the Intl JavaScript layer, returning the factory
 * function it evaluates to (owned).
 *
 * The blob is tried first and the source is the fallback. The fallback is not
 * defensive programming: QuickJS bytecode is only loadable by the engine build
 * that produced it, JS_ReadObject rejects a BC_VERSION mismatch with a clean
 * SyntaxError (vendor/quickjs-ng/quickjs.c:44091), and a module whose blob was
 * generated against a different engine revision must still work rather than
 * refusing to install Intl. The counters above are how you find out which path
 * a build is actually taking.
 */
JSValue loadFactory(JSContext *ctx) {
#if RNQJS_INTL_HAVE_BLOB
  JSValue fn =
      JS_ReadObject(ctx, kIntlBlob, kIntlBlobSize, JS_READ_OBJ_BYTECODE);
  if (!JS_IsException(fn)) {
    RNQJS_INTL_COUNT(blobLoads);
    return JS_EvalFunction(ctx, fn);
  }
  /* Swallow the SyntaxError; the source path below is a complete answer. */
  JS_FreeValue(ctx, JS_GetException(ctx));
#endif
  RNQJS_INTL_COUNT(sourceLoads);
  return JS_Eval(ctx, kIntlSource, strlen(kIntlSource), "rnqjs:intl", 0);
}

JSValue buildIntl(JSContext *ctx) {
  JSValue factory = loadFactory(ctx);
  if (JS_IsException(factory)) return factory;
  if (!JS_IsFunction(ctx, factory)) {
    JS_FreeValue(ctx, factory);
    return JS_ThrowInternalError(
        ctx, "Intl layer did not evaluate to a factory");
  }

  JSValue native = JS_NewObject(ctx);
  JS_SetPropertyFunctionList(
      ctx, native, kNativeFuncs,
      static_cast<int>(sizeof(kNativeFuncs) / sizeof(kNativeFuncs[0])));

  JSValue args[1] = {native};
  JSValue intl = JS_Call(ctx, factory, JS_UNDEFINED, 1, args);
  JS_FreeValue(ctx, native);
  JS_FreeValue(ctx, factory);
  RNQJS_INTL_COUNT(materializations);
  return intl;
}

int defineIntlData(JSContext *ctx, JSValue value /* consumed */) {
  JSValue global = JS_GetGlobalObject(ctx);
  JSAtom atom = JS_NewAtom(ctx, "Intl");
  /* The attributes ECMA-402 requires of globalThis.Intl. */
  int rc = JS_DefinePropertyValue(
      ctx, global, atom, value, JS_PROP_WRITABLE | JS_PROP_CONFIGURABLE);
  JS_FreeAtom(ctx, atom);
  JS_FreeValue(ctx, global);
  return rc;
}

JSValue intlGetter(
    JSContext *ctx, JSValueConst /*thisVal*/, int /*argc*/,
    JSValueConst * /*argv*/) {
  JSValue intl = buildIntl(ctx);
  if (JS_IsException(intl)) return intl;
  /*
   * Redefine the property from inside its own getter. Safe because the engine
   * duplicates the getter before calling it (quickjs.c:10376). Defining on the
   * global object rather than on the receiver means a read through an odd
   * receiver — Reflect.get(globalThis, 'Intl', someOtherObject) — cannot
   * install Intl somewhere else.
   */
  if (defineIntlData(ctx, JS_DupValue(ctx, intl)) < 0) {
    JS_FreeValue(ctx, intl);
    return JS_EXCEPTION;
  }
  return intl;
}

/**
 * The setter, which exists because `globalThis.Intl` must be **writable**.
 *
 * A getter-only accessor is not writable: assignment is a silent no-op in
 * sloppy mode and a TypeError in strict mode. Every polyfill that feature-
 * detects and then installs itself — which is precisely what formatjs's
 * should-polyfill path does — assigns over globalThis.Intl, so a getter-only
 * accessor would turn "app installs a polyfill" into "app throws". This was
 * measured as a failing case in the spike before the setter existed.
 *
 * Assignment never materializes the blob: a caller assigning over Intl does not
 * want ours.
 *
 * Registered as JS_CFUNC_generic, not JS_CFUNC_setter. Those protos have their
 * own C signatures — (ctx, this_val) and (ctx, this_val, val) — and registering
 * a 4-argument generic function under them reads the value out of the wrong
 * register, storing `undefined` with no error anywhere. The spike hit exactly
 * that.
 */
JSValue intlSetter(
    JSContext *ctx, JSValueConst /*thisVal*/, int argc, JSValueConst *argv) {
  RNQJS_INTL_COUNT(setterOverrides);
  JSValue v = argc > 0 ? JS_DupValue(ctx, argv[0]) : JS_UNDEFINED;
  return defineIntlData(ctx, v) < 0 ? JS_EXCEPTION : JS_UNDEFINED;
}

