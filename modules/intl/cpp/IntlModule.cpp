/*
 * react-native-quickjs-intl — the engine-facing half.
 *
 * PURPOSE
 *   Installs `globalThis.Intl` lazily and provides the JavaScript layer with a
 *   small object of native functions that reach the platform's CLDR database.
 *
 * THREE THINGS THIS FILE EXISTS TO DO
 *
 *   1. **Lazy first-use materialization from a module.** The engine gets this
 *      from JS_DefineAutoInitProperty, which is internal to quickjs.c and not
 *      in quickjs.h. The same effect is reachable from public API only:
 *      JS_DefinePropertyGetSet installs an accessor, and on first read the
 *      getter deserializes a precompiled bytecode blob with JS_ReadObject,
 *      evaluates it with JS_EvalFunction, and redefines `Intl` as a plain data
 *      property. Every later access is an ordinary property read.
 *
 *      MEASURED (bench/spikes/intl/self-replacing-accessor.c, M4 Pro,
 *      2026-07-26): an app that never touches Intl pays **152 ns once per
 *      runtime**, against a JS_NewRuntime+JS_NewContext floor of ~54 us. The
 *      getter is js_dup'd by the engine before it is called
 *      (vendor/quickjs-ng/quickjs.c:10376, whose comment reads "the field could
 *      be removed in the getter"), so replacing the property from inside its
 *      own getter is supported rather than merely observed to work.
 *
 *   2. **Real constructors.** A jsi::Function from createFromHostFunction is
 *      not a constructor. `new` against it does not produce an empty object —
 *      it produces no instance at all: `thisVal` is the constructor function
 *      itself, so writes to `this` mutate the constructor, and the result is
 *      whatever the host function returned, or `undefined` if it returned
 *      nothing. Return an object explicitly and its prototype is
 *      Object.prototype, so the assigned `.prototype` is never consulted and
 *      `instanceof` is false; `class S extends Thing {}` yields `undefined`
 *      from `new S()` rather than throwing. MEASURED.
 *      `Intl` is constructor-heavy, so this module does not use JSI for its
 *      class shapes at all. The shapes are declared as ordinary JavaScript in
 *      the precompiled blob, which the engine compiles into genuine
 *      constructors — `new`, `.prototype`, `instanceof` and subclassing all
 *      work with no special handling. Where a native constructor is needed,
 *      JS_NewCFunction2 with JS_CFUNC_constructor is available and is what
 *      would be used; stage one needs none.
 *
 *   3. **Deterministic release of platform formatters.** An NSDateFormatter or
 *      an android.icu.text.DateFormat is expensive and must not leak. Each
 *      handle lives in a JSValue of a dedicated JSClass whose finalizer calls
 *      dtf_close, so lifetime follows QuickJS's refcounting exactly and a
 *      formatter is released at the moment its JavaScript owner is.
 *
 * WHAT THIS DELIBERATELY DOES NOT DO
 *   - No ECMA-402 semantics. Not one option name, not one part type mapping
 *     decision, not one locale-negotiation rule lives here. All of it is in
 *     js/intl.js, so there is exactly one copy and it is the same on every
 *     platform.
 *   - No caching of formatters *except* the one place the option bag is a
 *     sound key: the fully-resolved NumberOptions that `nfOpen` already
 *     reads. Date/time caching stays in the backend, keyed by skeleton.
 *   - No thread affinity beyond the runtime's own. Every entry point here runs
 *     on the JS thread, called from JavaScript.
 */

