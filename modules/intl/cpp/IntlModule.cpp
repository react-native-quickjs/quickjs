/// Reads a UTF-8 string argument. undefined and null both yield the empty
/// string, which is how the platform interface spells "not requested".
std::string utf8Arg(JSContext *ctx, JSValueConst v) {
  if (JS_IsUndefined(v) || JS_IsNull(v)) return {};
  const char *s = JS_ToCString(ctx, v);
  if (s == nullptr) return {};
  std::string out(s);
  JS_FreeCString(ctx, s);
  return out;
}

/**
 * A borrowed, engine-owned view of a JSValue's UTF-16 text.
 *
 * PURPOSE
 *   Hand the platform layer the characters QuickJS already holds instead of a
 *   private copy of them.
 *
 *   MOTIVATED BY docs/intl-native-placement.md, which decomposed
 *   `localeCompare` at 688 ns and found the largest single item — ~303 ns,
 *   44% — was not the collation and not the crossing but a conversion
 *   pipeline: `utf16Arg` allocated a `std::u16string` and copied into it, and
 *   `fromU16` then allocated an `NSString` and copied again. Six heap
 *   allocations and six full copies of two short ASCII strings before
 *   Foundation looked at anything.
 *
 * WHAT IT BORROWS FROM
 *   `JS_ToCStringLenUTF16` returns a pointer into a `JSString` whose reference
 *   it holds (vendor/quickjs-ng/quickjs.c:5708). For an already-wide string
 *   that is the *original* string's storage and costs nothing; for a narrow
 *   (Latin-1) string the engine allocates a widened copy first. Removing that
 *   second case needs an engine-side accessor for the narrow bytes and is
 *   therefore engine work, not module work — see the handoff note in
 *   docs/intl-string-seam.md.
 *
 * INVARIANTS
 *   - The view is valid only for the lifetime of the U16Borrow. Never store
 *     it, never return it, never let it outlive the JSValue's argument frame.
 *   - Non-copyable, so it cannot be captured by accident.
 *   - `ok()` is false exactly when the engine threw (ToString on a value with
 *     a throwing `toString`, or OOM). The caller must propagate JS_EXCEPTION;
 *     the older `utf16Arg` swallowed that case into an empty string.
 *   - The empty string yields a non-null pointer and size 0, so a consumer
 *     never has to null-check `view().data()`.
 *
 * WHAT IT DELIBERATELY DOES NOT DO
 *   It does not NUL-terminate, it does not transcode, and it does not accept
 *   undefined/null the way `utf8Arg` does. A caller that needs "absent means
 *   empty" semantics wants `utf8Arg`.
 */
class U16Borrow {
 public:
  U16Borrow(JSContext *ctx, JSValueConst v) : ctx_(ctx) {
    size_t len = 0;
    p_ = JS_ToCStringLenUTF16(ctx, &len, v);
    n_ = p_ != nullptr ? len : 0;
  }
  ~U16Borrow() {
    if (p_ != nullptr) JS_FreeCStringUTF16(ctx_, p_);
  }
  U16Borrow(const U16Borrow &) = delete;
  U16Borrow &operator=(const U16Borrow &) = delete;

  bool ok() const {
    return p_ != nullptr;
  }
  std::u16string_view view() const {
    return std::u16string_view(reinterpret_cast<const char16_t *>(p_), n_);
  }

 private:
  JSContext *ctx_;
  const uint16_t *p_ = nullptr;
  size_t n_ = 0;
};

JSValue makeString(JSContext *ctx, const std::u16string &s) {
  return JS_NewStringUTF16(
      ctx, reinterpret_cast<const uint16_t *>(s.data()), s.size());
}

/// An empty platform answer means "no opinion" and becomes null, not "".
JSValue emitOptional(JSContext *ctx, const std::string &s) {
  return s.empty() ? JS_NULL : JS_NewStringLen(ctx, s.data(), s.size());
}

JSValue makeArray(JSContext *ctx, const std::vector<std::string> &v) {
  JSValue arr = JS_NewArray(ctx);
  for (uint32_t i = 0; i < v.size(); i++) {
    JS_SetPropertyUint32(
        ctx, arr, i, JS_NewStringLen(ctx, v[i].data(), v[i].size()));
  }
  return arr;
}

