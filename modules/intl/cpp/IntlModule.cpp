JSValue js_colCompare(
    JSContext *ctx, JSValueConst, int argc, JSValueConst *argv) {
  if (argc < 3) return JS_ThrowTypeError(ctx, "colCompare expects (h, a, b)");
  Collator *c = ColHandle::of(ctx, argv[0]);
  if (c == nullptr) return JS_EXCEPTION;
  /*
   * Borrowed, not copied. This is the hot path of `String.prototype.
   * localeCompare` and of every `Array.prototype.sort` comparator that uses
   * it, and the two `std::u16string` copies that used to be here were measured
   * as part of the ~303 ns C seam in docs/intl-native-placement.md.
   */
  // Ablation arm 3: return before either argument is read, so the arm measures
  // the JS shim, the bound call, js_call_c_function and ColHandle::of alone.
  if (RNQJS_ABL(3)) return JS_NewInt32(ctx, 0);
  const U16Borrow a(ctx, argv[1]);
  if (!a.ok()) return JS_EXCEPTION;
  const U16Borrow b(ctx, argv[2]);
  if (!b.ok()) return JS_EXCEPTION;
  // Ablation arm 4: arm 3 plus JS_ToCStringLenUTF16 on both arguments. The
  // difference between arms 4 and 3 is what reading the two strings costs.
  if (RNQJS_ABL(4)) {
    return JS_NewInt32(
        ctx, static_cast<int32_t>(a.view().size()) -
                 static_cast<int32_t>(b.view().size()));
  }
  return JS_NewInt32(ctx, c->compare(a.view(), b.view()));
}

