/*
 * A DateTimeFormatter lives in a JSValue of its own JSClass, so its lifetime is
 * the engine's refcounting and an NSDateFormatter or
 * android.icu.text.DateFormat is released at the moment its JavaScript owner
 * is. JS_NewClassID is process-global and JS_NewClass is per runtime, which is
 * why the id is a static initialised once and the class is registered into
 * every runtime.
 */
/*
 * One JSClass per handle type.
 *
 * A single shared class would be one class id and one finalizer, and it would
 * be wrong: JS_GetOpaque2 only checks the class id, so a shared class would let
 * `nfFormat(aCollator, 1)` static_cast a Collator to a NumberFormatter and call
 * through a garbage vtable. Distinct ids turn that into a clean TypeError, and
 * the JavaScript layer is not the only caller — the differential corpus passes
 * deliberately wrong handles.
 *
 * The template is what keeps five near-identical finalizers from being written
 * out five times; `Handle<T>::id` is a distinct static per T, which is exactly
 * the distinction being relied on.
 */
template <typename T>
struct Handle {
  static JSClassID id;
  static JSClassDef def;

  static void finalizer(JSRuntime * /*rt*/, JSValue val) {
    delete static_cast<T *>(JS_GetOpaque(val, id));
  }

  static void registerIn(JSRuntime *rt, const char *name) {
    if (id == 0) JS_NewClassID(rt, &id);
    def = JSClassDef{name, finalizer, nullptr, nullptr, nullptr};
    JS_NewClass(rt, id, &def);
  }

  static T *of(JSContext *ctx, JSValueConst v) {
    return static_cast<T *>(JS_GetOpaque2(ctx, v, id));
  }

  /// Wraps an owned pointer. Consumes `p` on success and on failure alike.
  static JSValue wrap(JSContext *ctx, std::unique_ptr<T> p) {
    if (!p) return JS_NULL;
    JSValue obj = JS_NewObjectClass(ctx, static_cast<int>(id));
    if (JS_IsException(obj)) return obj;  // ~unique_ptr releases the platform
    JS_SetOpaque(obj, p.release());
    return obj;
  }
};
template <typename T>
JSClassID Handle<T>::id = 0;
template <typename T>
JSClassDef Handle<T>::def{};

using DtfHandle = Handle<DateTimeFormatter>;
using NfHandle = Handle<NumberFormatter>;
using ColHandle = Handle<Collator>;
using RtfHandle = Handle<RelativeTimeFormatter>;
using LfHandle = Handle<ListFormatter>;

DateTimeFormatter *handleOf(JSContext *ctx, JSValueConst v) {
  return DtfHandle::of(ctx, v);
}

