/*
 * `(1234.5).toLocaleString()`, `"a".localeCompare("b")`,
 * `new Date().toLocaleDateString()` and the two locale case mappings are what
 * an application actually calls. js/intl.js replaces all of them — but it only
 * runs when `Intl` is first *read*, and a program that calls
 * `(1234.5).toLocaleString("de")` without ever mentioning `Intl` never triggers
 * that read.
 *
 * MEASURED, and it was a real bug rather than a hypothetical one:
 *
 *   $ intl-cli-apple -e '''print((88776655n).toLocaleString("en",{maximumSignificantDigits:4}));
 *                         print(new Intl.NumberFormat("en",{maximumSignificantDigits:4}).format(88776655n));
 *                         print((12345n).toLocaleString("en"));'''
 *   88776655        <- the engine'''s stub: options ignored
 *   88,780,000      <- reading Intl materialized the layer
 *   12,345          <- the same call, now correct
 *
 * The first and third lines are the same call with different answers, and the
 * only difference is whether `Intl` had been touched. Three test262 files see
 * it; an application would see it far more often, because the whole point of
 * this module is that installing it changes the behaviour of code that never
 * mentions `Intl`.
 *
 * THE FIX, AND WHY IT IS A TRAMPOLINE RATHER THAN AN EAGER INSTALL
 *   Installing the real implementations at module-install time would mean
 *   materializing the whole ECMA-402 layer in every runtime, which is exactly
 *   the 67 us this design pays 152 ns to avoid. So each method is replaced with
 *   a tiny native trampoline that, on its first call, reads `globalThis.Intl`
 *   (running the accessor and therefore installing the real methods) and then
 *   re-dispatches. From the second call onwards the trampoline is gone: the
 *   property holds the JavaScript implementation.
 *
 *   The engine'''s original method is carried in the trampoline'''s own function
 *   data, so the one case where materialization does not replace the property —
 *   an application that assigned over `globalThis.Intl` before calling any of
 *   these, which suppresses our layer by design — degrades to the engine'''s
 *   locale-ignoring behaviour instead of recursing forever. That is the same
 *   behaviour the application would have had without this module.
 */
struct LocaleHook {
  const char *constructorName;
  const char *methodName;
  int length;
  /**
   * %TypedArray%.prototype has no global binding, so it is reached as the
   * prototype *of* Int8Array.prototype. Spelling that here rather than
   * hard-coding a second lookup path keeps every hook in one table, which is
   * what makes the table checkable by reading it.
   */
  bool viaPrototypeOfPrototype;
};

const LocaleHook kLocaleHooks[] = {
    {"Number", "toLocaleString", 0, false},
    {"BigInt", "toLocaleString", 0, false},
    {"String", "localeCompare", 1, false},
    {"String", "toLocaleUpperCase", 0, false},
    {"String", "toLocaleLowerCase", 0, false},
    {"Date", "toLocaleString", 0, false},
    {"Date", "toLocaleDateString", 0, false},
    {"Date", "toLocaleTimeString", 0, false},
    /*
     * Array and %TypedArray%. ECMA-402 requires these to forward `locales` and
     * `options` to each element's own toLocaleString; the plain ECMAScript
     * versions in the engine call it with no arguments. MEASURED:
     * `[0].toLocaleString("th-u-nu-thai", {minimumFractionDigits: 3})` returned
     * "0" where `(0).toLocaleString(...)` returned Thai digits — the two sides
     * of test262's own assertion.
     */
    {"Array", "toLocaleString", 0, false},
    {"Int8Array", "toLocaleString", 0, true},
};

/// The prototype object a hook installs onto, or JS_UNDEFINED.
JSValue prototypeFor(
    JSContext *ctx, JSValueConst global, const LocaleHook &hook) {
  JSValue ctor = JS_GetPropertyStr(ctx, global, hook.constructorName);
  if (!JS_IsObject(ctor)) {
    /* BigInt is absent from a build compiled without it, and a build without
       typed arrays has no Int8Array. Skipping is correct: there is no prototype
       to hook. */
    JS_FreeValue(ctx, ctor);
    return JS_UNDEFINED;
  }
  JSValue proto = JS_GetPropertyStr(ctx, ctor, "prototype");
  JS_FreeValue(ctx, ctor);
  if (hook.viaPrototypeOfPrototype && JS_IsObject(proto)) {
    JSValue outer = JS_GetPrototype(ctx, proto);
    JS_FreeValue(ctx, proto);
    proto = outer;
  }
  return proto;
}

JSValue localeTrampoline(
    JSContext *ctx, JSValueConst thisVal, int argc, JSValueConst *argv,
    int magic, JSValue *funcData) {
  const LocaleHook &hook = kLocaleHooks[magic];

  JSValue global = JS_GetGlobalObject(ctx);
  /* Reading the property is what runs the accessor and materializes the layer. */
  JSValue intl = JS_GetPropertyStr(ctx, global, "Intl");

  /*
   * Did OUR layer run?
   *
   * `__rnqjsBackend` is the diagnostics hook js/intl.js installs on the Intl
   * namespace, and its presence is the discriminator. It is needed because
   * `globalThis.Intl` is writable by design — a feature-detecting polyfill
   * assigns over it, which turns the accessor into a data property and means
   * our layer never runs and never replaces these prototype methods. Without
   * this check the trampoline would look itself up and recurse forever.
   *
   * The alternative discriminators were all worse: comparing the looked-up
   * function against the trampoline needs a self-reference (a retain cycle, and
   * two constructions to obtain), and a recursion-depth counter cannot survive
   * into the dispatched call without also suppressing the legitimate re-entry
   * of Array.prototype.toLocaleString.
   */
  bool ours = false;
  if (JS_IsObject(intl)) {
    JSValue probe = JS_GetPropertyStr(ctx, intl, "__rnqjsBackend");
    ours = JS_IsFunction(ctx, probe);
    JS_FreeValue(ctx, probe);
  }
  JS_FreeValue(ctx, intl);

  JSValue target = JS_UNDEFINED;
  if (ours) {
    JSValue proto = prototypeFor(ctx, global, hook);
    if (JS_IsObject(proto)) {
      target = JS_GetPropertyStr(ctx, proto, hook.methodName);
    }
    JS_FreeValue(ctx, proto);
  }
  JS_FreeValue(ctx, global);

  if (!JS_IsFunction(ctx, target)) {
    /* No layer, or it did not install this method: the engine's own behaviour,
       which is what the program would have had without this module. */
    JS_FreeValue(ctx, target);
    target = JS_DupValue(ctx, funcData[0]);
  }
  if (!JS_IsFunction(ctx, target)) {
    JS_FreeValue(ctx, target);
    return JS_ThrowTypeError(
        ctx, "%s.prototype.%s is not callable", hook.constructorName,
        hook.methodName);
  }
  JSValue result = JS_Call(ctx, target, thisVal, argc, argv);
  JS_FreeValue(ctx, target);
  return result;
}

void installLocaleHooks(JSContext *ctx) {
  JSValue global = JS_GetGlobalObject(ctx);
  for (int i = 0;
       i < static_cast<int>(sizeof(kLocaleHooks) / sizeof(kLocaleHooks[0]));
       i++) {
    const LocaleHook &hook = kLocaleHooks[i];
    JSValue proto = prototypeFor(ctx, global, hook);
    if (!JS_IsObject(proto)) {
      JS_FreeValue(ctx, proto);
      continue;
    }
    JSValue original = JS_GetPropertyStr(ctx, proto, hook.methodName);
    JSValueConst data[1] = {original};
    /*
     * NewCFunctionData2, for the name. A function created by
     * JS_NewCFunctionData has an empty `name`, and test262 checks the name
     * descriptor of every one of these methods
     * (BigInt/prototype/toLocaleString/name.js and friends). The trampoline is
     * observable through exactly that one property until it is replaced.
     */
    JSValue fn = JS_NewCFunctionData2(
        ctx, localeTrampoline, hook.methodName, hook.length, i, 1, data);
    JS_FreeValue(ctx, original);
    if (!JS_IsException(fn)) {
      /* The attributes ECMAScript gives these methods: writable, not
         enumerable, configurable. js/intl.js redefines them with exactly the
         same attributes, so the replacement is invisible to a descriptor check. */
      JS_DefinePropertyValueStr(
          ctx, proto, hook.methodName, fn,
          JS_PROP_WRITABLE | JS_PROP_CONFIGURABLE);
    }
    JS_FreeValue(ctx, proto);
  }
  JS_FreeValue(ctx, global);
}

void installInto(JSContext *ctx) {
  if (ctx == nullptr) return;

  JSRuntime *rt = JS_GetRuntime(ctx);
  DtfHandle::registerIn(rt, "Intl.DateTimeFormat.Handle");
  NumHandle::registerIn(rt, "Intl.NumberFormat.Handle");
  ColHandle::registerIn(rt, "Intl.Collator.Handle");
  RtfHandle::registerIn(rt, "Intl.RelativeTimeFormat.Handle");
  LfHandle::registerIn(rt, "Intl.ListFormat.Handle");

  JSValue global = JS_GetGlobalObject(ctx);
  JSAtom atom = JS_NewAtom(ctx, "Intl");
  JSValue getter =
      JS_NewCFunction2(ctx, intlGetter, "get Intl", 0, JS_CFUNC_generic, 0);
  JSValue setter =
      JS_NewCFunction2(ctx, intlSetter, "set Intl", 1, JS_CFUNC_generic, 0);
  /* JS_PROP_CONFIGURABLE is load-bearing: without it the accessor cannot be
     replaced by the data property and the whole mechanism silently degrades
     into a getter call on every access. */
  JS_DefinePropertyGetSet(
      ctx, global, atom, getter, setter, JS_PROP_CONFIGURABLE);
  JS_FreeAtom(ctx, atom);
  JS_FreeValue(ctx, global);
  installLocaleHooks(ctx);
  RNQJS_INTL_COUNT(accessorInstalls);
}

