/*
 * These factories take a JavaScript *object* where dtfOpen takes eight
 * positional arguments, and the difference is deliberate rather than
 * inconsistent. NumberOptions has twenty fields; twenty positional arguments is
 * a shape where adding a field in the middle silently shifts every later one,
 * and this file has already shipped one bug of exactly that kind (the setter
 * registered under the wrong JSCFunctionEnum read its value out of the wrong
 * register). Reading named properties here costs one atom lookup per field,
 * once per formatter construction, and never on a format path.
 *
 * The platform layer still receives a plain struct and still never sees a
 * JSValue — that invariant is what keeps the Objective-C and JNI code out of
 * the engine's refcounting rules, and it is unchanged.
 */
std::string strField(JSContext *ctx, JSValueConst obj, const char *name) {
  JSValue v = JS_GetPropertyStr(ctx, obj, name);
  std::string out = utf8Arg(ctx, v);
  JS_FreeValue(ctx, v);
  return out;
}

int32_t intField(
    JSContext *ctx, JSValueConst obj, const char *name, int32_t fallback) {
  JSValue v = JS_GetPropertyStr(ctx, obj, name);
  if (JS_IsUndefined(v) || JS_IsNull(v)) {
    JS_FreeValue(ctx, v);
    return fallback;
  }
  int32_t out = fallback;
  if (JS_ToInt32(ctx, &out, v) < 0) out = fallback;
  JS_FreeValue(ctx, v);
  return out;
}

bool boolField(JSContext *ctx, JSValueConst obj, const char *name) {
  JSValue v = JS_GetPropertyStr(ctx, obj, name);
  const bool out = JS_ToBool(ctx, v) > 0;
  JS_FreeValue(ctx, v);
  return out;
}

std::u16string utf16Arg(JSContext *ctx, JSValueConst v) {
  size_t len = 0;
  const uint16_t *p = JS_ToCStringLenUTF16(ctx, &len, v);
  if (p == nullptr) return {};
  std::u16string out(reinterpret_cast<const char16_t *>(p), len);
  JS_FreeCStringUTF16(ctx, p);
  return out;
}

